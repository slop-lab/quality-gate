import { cp, mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, join, relative, sep } from "node:path";
import type { Diagnostic, Rule, RuleContext } from "@quality-gate/core";

export interface PnpmLockfileIsCurrentOptions {
  pnpmCommand?: string;
  ignoredShadowDirectories?: string[];
}

const defaultPnpmLockfileOptions: Required<PnpmLockfileIsCurrentOptions> = {
  pnpmCommand: "pnpm",
  ignoredShadowDirectories: [".git", ".quality-gate", "dist", "node_modules"],
};

export const noNpmLockWithPnpmRule: Rule = {
  metadata: {
    id: "package-manager/no-npm-lock-with-pnpm",
    name: "No npm lockfile with pnpm workspace",
    description:
      "Reports package-lock.json when pnpm-workspace.yaml is present.",
    defaultSeverity: "error",
    supports: ["changed", "full"],
    scope: "repo",
    requires: ["fileMetadata"],
    fixable: "edit",
  },
  async check(context) {
    if (
      context.mode === "changed" &&
      !hasChangedPath(context, ["package-lock.json", "pnpm-workspace.yaml"])
    ) {
      return [];
    }

    if (
      !(await context.fs.exists("pnpm-workspace.yaml")) ||
      !(await context.fs.exists("package-lock.json"))
    ) {
      return [];
    }

    return [
      {
        ruleId: noNpmLockWithPnpmRule.metadata.id,
        severity: context.severity,
        message: "pnpm workspace should not contain npm package-lock.json.",
        path: "package-lock.json",
        scope: "repo",
        suggestedFix: {
          message:
            "Delete package-lock.json and use pnpm-lock.yaml as the single package manager lockfile.",
          edits: [
            {
              type: "deleteFile",
              path: "package-lock.json",
            },
          ],
        },
      },
    ];
  },
};

export const pnpmLockfileIsCurrentRule: Rule<PnpmLockfileIsCurrentOptions> = {
  metadata: {
    id: "pnpm/lockfile-is-current",
    name: "pnpm lockfile is current",
    description: "Reports pnpm-lock.yaml when pnpm would rewrite it.",
    defaultSeverity: "error",
    supports: ["changed", "full"],
    scope: "repo",
    requires: ["fileContent", "process"],
    fixable: "suggestion",
    defaultOptions: defaultPnpmLockfileOptions,
  },
  async check(context) {
    const options = {
      ...defaultPnpmLockfileOptions,
      ...context.options,
    };

    if (context.mode === "changed" && !hasRelevantPnpmLockfileChange(context)) {
      return [];
    }

    if (
      !(await context.fs.exists("pnpm-workspace.yaml")) ||
      !(await context.fs.exists("pnpm-lock.yaml"))
    ) {
      return [];
    }

    const shadowRoot = await createShadowWorkspace(
      context.root,
      options.ignoredShadowDirectories,
    );
    try {
      const result = await context.process.exec({
        command: options.pnpmCommand,
        args: ["install", "--lockfile-only", "--ignore-scripts"],
        cwd: shadowRoot,
      });

      if (result.exitCode !== 0) {
        return [
          diagnostic(
            context,
            "pnpm-lock.yaml",
            "pnpm could not validate pnpm-lock.yaml.",
            {
              exitCode: result.exitCode,
              stdout: result.stdout,
              stderr: result.stderr,
            },
          ),
        ];
      }

      const current = await context.fs.readFile("pnpm-lock.yaml");
      const formatted = await readFile(
        join(shadowRoot, "pnpm-lock.yaml"),
        "utf8",
      );

      if (current === formatted) {
        return [];
      }

      return [
        diagnostic(
          context,
          "pnpm-lock.yaml",
          "pnpm-lock.yaml differs from the file generated by pnpm install --lockfile-only --ignore-scripts.",
        ),
      ];
    } finally {
      await rm(shadowRoot, { recursive: true, force: true });
    }
  },
};

export const packageManagerRules = [
  noNpmLockWithPnpmRule,
  pnpmLockfileIsCurrentRule,
];

function hasRelevantPnpmLockfileChange(context: RuleContext): boolean {
  return context.changes.some((change) => {
    const paths = [change.path, change.oldPath].filter((path): path is string =>
      Boolean(path),
    );
    return paths.some(
      (path) =>
        path === "pnpm-lock.yaml" ||
        path === "pnpm-workspace.yaml" ||
        basename(path) === "package.json",
    );
  });
}

function hasChangedPath(context: RuleContext, paths: string[]): boolean {
  const candidates = new Set(paths);
  return context.changes.some(
    (change) =>
      candidates.has(change.path) ||
      (change.oldPath && candidates.has(change.oldPath)),
  );
}

function diagnostic(
  context: RuleContext,
  path: string,
  message: string,
  metadata?: Record<string, unknown>,
): Diagnostic {
  return {
    ruleId: pnpmLockfileIsCurrentRule.metadata.id,
    severity: context.severity,
    message,
    path,
    scope: "repo",
    suggestedFix: {
      message:
        "Run pnpm install --lockfile-only --ignore-scripts and commit the resulting pnpm-lock.yaml.",
    },
    metadata,
  };
}

async function createShadowWorkspace(
  root: string,
  ignoredDirectories: string[],
): Promise<string> {
  const shadowRoot = await mkdtemp(join(tmpdir(), "quality-gate-pnpm-"));
  await cp(root, shadowRoot, {
    recursive: true,
    filter: (sourcePath) =>
      shouldCopyPath(root, sourcePath, ignoredDirectories),
  });
  return shadowRoot;
}

function shouldCopyPath(
  root: string,
  sourcePath: string,
  ignoredDirectories: string[],
): boolean {
  const relativePath = relative(root, sourcePath);
  if (!relativePath) {
    return true;
  }

  const segments = relativePath.split(sep);
  return !segments.some((segment) => ignoredDirectories.includes(segment));
}
